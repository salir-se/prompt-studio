#!/usr/bin/env bun
/**
 * Assembles the publishable npm package for Prompt Studio.
 *
 * The package — `@salir/prompt-studio` on the public npm registry — is the editor as a
 * self-contained tarball, runnable with `bunx` (Bun is the only supported runtime). The server and CLI are fully bundled, so the
 * package never needs (or carries) a node_modules directory. The tarball scans below also refuse
 * stray prompt-content trees from the original private build, as a second line of defence next to
 * `scripts/check-public-content.ts`.
 *
 * Package layout (mirrors the repo-relative paths the server resolves at runtime):
 *
 *   bin/prompt-studio.js          checked-in launcher (bin/prompt-studio.mjs, copied verbatim)
 *   bin/prompt-studio-cli.js      checked-in launcher (bin/prompt-studio-cli.mjs)
 *   server/main.js                bun build --target=bun bundle of server/main.ts
 *   cli/main.js                   bun build --target=bun bundle of cli/main.ts
 *   dist/                         vite build output (the SPA)
 *   studio-manifest/manifest.json the shipped default manifest (ADR-235 metadata only)
 *   README.md, LICENSE, NOTICE    copied from the repository root
 *   package.json                  generated by buildPackageJson below
 *
 * Everything under `import.meta.main` is process wiring (execSync of vite/bun build/bun pm pack);
 * the exported helpers are pure and unit-tested in build-npm-package.test.ts.
 */

import { execFileSync } from 'node:child_process';
import {
  chmodSync,
  copyFileSync,
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/** Published under the GitHub organization's npm scope. */
export const NPM_PACKAGE_NAME = '@salir/prompt-studio';

export const NPM_PUBLIC_REGISTRY = 'https://registry.npmjs.org';

/** Prompt-content trees of the original private build. None may appear in the published tarball. */
export const PROTECTED_TARBALL_PATHS = [
  'packages/prompts/src/blueprints',
  'packages/skills/skills',
  'docs/prompts',
] as const;

/** Files the published tarball must contain for the studio to boot (asserted after packing). */
export const REQUIRED_PACKAGE_FILES = [
  'bin/prompt-studio.js',
  'bin/prompt-studio-cli.js',
  'bin/prompt-studio-mcp.js',
  'server/main.js',
  'mcp/main.js',
  'cli/main.js',
  'dist/index.html',
  'studio-manifest/manifest.json',
  'README.md',
  'LICENSE',
  'NOTICE',
] as const;

/** Validates a release version (strips the release tag's `v` prefix); rejects everything else. */
export function normalizeVersion(raw: string): string {
  const trimmed = raw.trim();
  const candidate = trimmed.startsWith('v') ? trimmed.slice(1) : trimmed;
  if (!/^\d+\.\d+\.\d+(-[\w.-]+)?$/.test(candidate)) {
    throw new Error(`Invalid package version: ${JSON.stringify(trimmed)} (expected X.Y.Z or vX.Y.Z)`);
  }
  return candidate;
}

/** Builds the publishable package manifest. `private` is deliberately absent: npm refuses to
 * publish a `private: true` package. */
export function buildPackageJson(version: string): Record<string, unknown> {
  return {
    name: NPM_PACKAGE_NAME,
    version,
    description:
      'Prompt Studio — a visual prompt builder for AI agents: your agent composes prompts through MCP, you see structure, variables and checks live, then run, evaluate, version and open GitHub PRs.',
    keywords: [
      'prompt-engineering',
      'mcp',
      'model-context-protocol',
      'llm',
      'claude-code',
      'codex',
      'prompt-testing',
      'evals',
      'ai-agents',
    ],
    type: 'module',
    license: 'Apache-2.0',
    repository: { type: 'git', url: 'git+https://github.com/salir-se/prompt-studio.git' },
    homepage: 'https://github.com/salir-se/prompt-studio#readme',
    bugs: { url: 'https://github.com/salir-se/prompt-studio/issues' },
    engines: { bun: '>=1.4.4' },
    bin: {
      'prompt-studio': 'bin/prompt-studio.js',
      'prompt-studio-cli': 'bin/prompt-studio-cli.js',
      'prompt-studio-mcp': 'bin/prompt-studio-mcp.js',
    },
    files: ['bin', 'cli', 'dist', 'mcp', 'server', 'studio-manifest', 'README.md', 'LICENSE', 'NOTICE'],
    publishConfig: { registry: NPM_PUBLIC_REGISTRY, access: 'public' },
  };
}

/** the tarball lists files as `package/<relative path>`; normalize to package-relative. */
export function stripPackagePrefix(filePath: string): string {
  return filePath.startsWith('package/') ? filePath.slice('package/'.length) : filePath;
}

/** Returns which ADR-204 protected content paths appear in the (normalized) file list. */
export function findProtectedTarballPaths(files: readonly string[]): string[] {
  return PROTECTED_TARBALL_PATHS.filter((protectedPath) =>
    files.some((file) => file === protectedPath || file.startsWith(`${protectedPath}/`)),
  );
}

/** The package must be self-contained — any node_modules entry means a broken bundle. */
export function findDisallowedTarballEntries(files: readonly string[]): string[] {
  return files.filter((file) => file === 'node_modules' || file.startsWith('node_modules/'));
}

/** Returns each REQUIRED_PACKAGE_FILES entry absent from the (normalized) file list. */
export function missingRequiredPackageFiles(files: readonly string[]): string[] {
  return REQUIRED_PACKAGE_FILES.filter((required) => !files.includes(required));
}

/** Recursively lists files under `dir` as package-relative paths (used by the local dry scan). */
export function listPackageFiles(dir: string): string[] {
  const files: string[] = [];
  const walk = (relative: string): void => {
    const full = path.join(dir, relative);
    if (statSync(full).isDirectory()) {
      for (const entry of readdirSync(full)) walk(relative.length > 0 ? `${relative}/${entry}` : entry);
    } else {
      files.push(relative);
    }
  };
  walk('');
  return files.sort();
}

function run(cwd: string, command: string, args: readonly string[]): string {
  return execFileSync(command, args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] });
}

async function main(): Promise<void> {
  const scriptDir = path.dirname(fileURLToPath(import.meta.url));
  const appRoot = path.resolve(scriptDir, '..');
  const repoRoot = appRoot;

  const versionFlagIndex = process.argv.indexOf('--version');
  const rawVersion =
    versionFlagIndex >= 0 ? (process.argv[versionFlagIndex + 1] ?? '') : (process.env.PROMPT_STUDIO_NPM_VERSION ?? '');
  const version = normalizeVersion(rawVersion);

  const stageRoot = path.join(repoRoot, '.output', 'prompt-studio-npm');
  const pkgDir = path.join(stageRoot, 'package');
  rmSync(stageRoot, { recursive: true, force: true });
  for (const dir of ['bin', 'cli', 'mcp', 'server', 'studio-manifest'].map((entry) => path.join(pkgDir, entry))) {
    mkdirSync(dir, { recursive: true });
  }

  // 1. SPA — `build:container` (vite build --mode container): the volume-first build whose
  //    catalog resolves prompt text from the operator's repo at runtime (ADR-204 §1/§7), not a
  //    build-time snapshot. Do not "simplify" this to the plain `build` script.
  console.log('[npm-package] building SPA (vite build)...');
  run(appRoot, 'bun', ['run', 'build']);
  if (!existsSync(path.join(appRoot, 'dist', 'index.html'))) {
    throw new Error('vite build did not produce dist/index.html');
  }
  cpSync(path.join(appRoot, 'dist'), path.join(pkgDir, 'dist'), { recursive: true });

  // 2. Server + CLI bundles — everything inlined so the package carries no node_modules.
  console.log('[npm-package] bundling server and CLI (bun build --target=bun)...');
  run(appRoot, 'bun', [
    'build',
    'server/main.ts',
    '--target=bun',
    '--format=esm',
    '--outfile',
    path.join(pkgDir, 'server', 'main.js'),
  ]);
  run(appRoot, 'bun', [
    'build',
    'packages/mcp-server/src/index.ts',
    '--target=bun',
    '--format=esm',
    '--outfile',
    path.join(pkgDir, 'mcp', 'main.js'),
  ]);
  run(appRoot, 'bun', [
    'build',
    'cli/main.ts',
    '--target=bun',
    '--format=esm',
    '--outfile',
    path.join(pkgDir, 'cli', 'main.js'),
  ]);

  // 3. Launchers, manifest, README, package.json.
  copyFileSync(path.join(appRoot, 'bin', 'prompt-studio.mjs'), path.join(pkgDir, 'bin', 'prompt-studio.js'));
  copyFileSync(path.join(appRoot, 'bin', 'prompt-studio-cli.mjs'), path.join(pkgDir, 'bin', 'prompt-studio-cli.js'));
  copyFileSync(path.join(appRoot, 'bin', 'prompt-studio-mcp.mjs'), path.join(pkgDir, 'bin', 'prompt-studio-mcp.js'));
  for (const bin of ['prompt-studio.js', 'prompt-studio-cli.js', 'prompt-studio-mcp.js']) {
    // the packer preserves the file mode; be explicit rather than relying on the
    // checkout's umask.
    chmodSync(path.join(pkgDir, 'bin', bin), 0o755);
  }
  copyFileSync(
    path.join(appRoot, 'src', 'manifest', 'default.manifest.json'),
    path.join(pkgDir, 'studio-manifest', 'manifest.json'),
  );
  for (const guide of ['README.md', 'LICENSE', 'NOTICE']) {
    copyFileSync(path.join(appRoot, guide), path.join(pkgDir, guide));
  }
  writeFileSync(path.join(pkgDir, 'package.json'), `${JSON.stringify(buildPackageJson(version), null, 2)}\n`);

  // 4. Pre-pack content scan over the assembled tree (same checks the tarball gets in CI —
  //    failing here keeps the failure next to the assembly that caused it).
  const files = listPackageFiles(pkgDir);
  const violations = [
    ...findProtectedTarballPaths(files).map((found) => `protected content path shipped as files: ${found}`),
    ...findDisallowedTarballEntries(files).map((found) => `node_modules entry in package: ${found}`),
    ...missingRequiredPackageFiles(files).map((missing) => `required file missing: ${missing}`),
  ];
  if (violations.length > 0) {
    for (const violation of violations) console.error(`[npm-package] ${violation}`);
    throw new Error('npm package assembly violates the ADR-204 package contract (see errors above)');
  }

  // 5. Pack. `bun pm pack --quiet` prints only the tarball file name.
  console.log('[npm-package] packing...');
  const packedName = run(pkgDir, 'bun', ['pm', 'pack', '--quiet']).trim().split('\n').at(-1) ?? '';
  const tarball = path.isAbsolute(packedName) ? packedName : path.join(pkgDir, packedName);
  if (!packedName || !existsSync(tarball)) {
    throw new Error(`bun pm pack did not produce the expected tarball (${tarball})`);
  }

  console.log('[npm-package] OK');
  console.log(`  version : ${version}`);
  console.log(`  package : ${pkgDir}`);
  console.log(`  tarball : ${tarball}`);
  console.log('  next    : bun scripts/smoke-npm-package.ts (boots this tarball under Bun)');
}

// `import.meta.main` is Bun-only — exactly right here: the script runs under Bun, and a vitest
// import of this module (the unit tests) must not execute any of the wiring above.
if (import.meta.main) {
  main().catch((error: unknown) => {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  });
}
